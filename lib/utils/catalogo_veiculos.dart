  /// Retorna o mapa de marcas -> modelos de acordo com o tipo de veículo.
  static Map<String, List<String>> mapaPorTipo(TipoVeiculo tipo) {
    switch (tipo) {
      case TipoVeiculo.carro:
        return _carrosPorMarca;
      case TipoVeiculo.moto:
        return _motosPorMarca;
      case TipoVeiculo.caminhao:
        return _caminhoesPorMarca;
    }
  }

  /// Lista de marcas populares ordenadas para o tipo de veículo.
  static List<String> marcasPara(TipoVeiculo tipo) {
    return mapaPorTipo(tipo).keys.toList();
  }

  /// Lista de modelos para uma marca específica (ou todos os modelos do tipo se a marca não for encontrada).
  static List<String> modelosPara(TipoVeiculo tipo, String marca) {
    final mapa = mapaPorTipo(tipo);
    final marcaLimpa = marca.trim().toLowerCase();
    if (marcaLimpa.isEmpty) {
      return mapa.values.expand((x) => x).toList();
    }

    for (final entrada in mapa.entries) {
      if (entrada.key.toLowerCase() == marcaLimpa ||
          entrada.key.toLowerCase().contains(marcaLimpa) ||
          marcaLimpa.contains(entrada.key.toLowerCase())) {
        return entrada.value;
      }
    }
    return [];
  }

  /// Busca a marca correspondente a um modelo, caso o usuário escolha o modelo antes da marca.
  static String? encontrarMarcaDoModelo(TipoVeiculo tipo, String modelo) {
    final mapa = mapaPorTipo(tipo);
    final modLimpo = modelo.trim().toLowerCase();
    for (final entrada in mapa.entries) {
      if (entrada.value.any((m) => m.toLowerCase() == modLimpo)) {
        return entrada.key;
      }
    }
    return null;
  }
